/** "+2" או "−1", מבודד משמאל לימין כדי שבתוך טקסט עברי הסימן לא יקפוץ לצד השני ("1−") */
function signed(n: number): string {
  return `⁦${n > 0 ? '+' : n < 0 ? '−' : ''}${Math.abs(n)}⁩`;
}

